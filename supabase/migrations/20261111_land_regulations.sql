-- 地政士法規專區：法條、個人筆記與參考連結。
-- 欄位格式與既有教育法規頁面使用的 clauses 資料表一致。

create table if not exists public.land_registration_rules_clauses (
  id bigint generated by default as identity primary key,
  article_num text not null,
  title text,
  content text,
  chapter_name text,
  section_name text,
  notes text default '',
  urls jsonb not null default '[]'::jsonb,
  created_at timestamptz not null default now()
);

create table if not exists public.land_act_clauses (
  id bigint generated by default as identity primary key,
  article_num text not null,
  title text,
  content text,
  chapter_name text,
  section_name text,
  notes text default '',
  urls jsonb not null default '[]'::jsonb,
  created_at timestamptz not null default now()
);

create table if not exists public.land_tax_act_clauses (
  id bigint generated by default as identity primary key,
  article_num text not null,
  title text,
  content text,
  chapter_name text,
  section_name text,
  notes text default '',
  urls jsonb not null default '[]'::jsonb,
  created_at timestamptz not null default now()
);

create unique index if not exists land_registration_rules_article_num_key on public.land_registration_rules_clauses (article_num);
create unique index if not exists land_act_article_num_key on public.land_act_clauses (article_num);
create unique index if not exists land_tax_act_article_num_key on public.land_tax_act_clauses (article_num);

grant select, insert, update, delete on public.land_registration_rules_clauses to anon, authenticated;
grant select, insert, update, delete on public.land_act_clauses to anon, authenticated;
grant select, insert, update, delete on public.land_tax_act_clauses to anon, authenticated;
grant usage, select on sequence public.land_registration_rules_clauses_id_seq to anon, authenticated;
grant usage, select on sequence public.land_act_clauses_id_seq to anon, authenticated;
grant usage, select on sequence public.land_tax_act_clauses_id_seq to anon, authenticated;
