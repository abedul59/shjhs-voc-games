-- 口說學霸－多元評量：七、八、九年級獨立句子題庫。

create table if not exists public.speakno1_sentences (
  id bigint generated by default as identity primary key,
  grade smallint not null check (grade in (7, 8, 9)),
  english text not null check (length(trim(english)) > 0),
  chinese text not null default '',
  sort_order integer not null default 0,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now()
);

create index if not exists speakno1_sentences_grade_sort_idx
  on public.speakno1_sentences (grade, sort_order, id);

grant select, insert, update, delete on public.speakno1_sentences to anon, authenticated;
grant usage, select on sequence public.speakno1_sentences_id_seq to anon, authenticated;

comment on table public.speakno1_sentences is
  '口說學霸多元評量句子；grade 分別為 7、8、9。';
