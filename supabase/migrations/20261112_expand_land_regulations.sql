-- 擴充地政士法規專區。所有法規共用同一組 CSV 欄位與閱讀／筆記功能。
-- 本 migration 可重複執行，不會刪除或覆蓋既有法規資料。

do $$
declare
  relation_name text;
  sequence_name text;
begin
  foreach relation_name in array array[
    'trust_act_clauses',
    'land_act_enforcement_act_clauses',
    'equalization_land_rights_act_clauses',
    'equalization_land_rights_enforcement_rules_clauses',
    'land_expropriation_act_clauses',
    'land_expropriation_act_enforcement_rules_clauses',
    'land_tax_act_enforcement_rules_clauses',
    'deed_tax_act_clauses',
    'house_tax_act_clauses',
    'estate_gift_tax_act_clauses',
    'estate_gift_tax_act_enforcement_rules_clauses',
    'land_administration_agent_act_clauses',
    'land_administration_agent_act_enforcement_rules_clauses',
    'cadastral_survey_implementation_rules_clauses',
    'urban_planning_act_clauses',
    'urban_planning_act_enforcement_rules_clauses',
    'regional_plan_act_clauses',
    'regional_plan_act_enforcement_rules_clauses',
    'spatial_planning_act_clauses'
  ]
  loop
    execute format(
      'create table if not exists public.%I (
        id bigint generated by default as identity primary key,
        article_num text not null unique,
        title text,
        content text,
        chapter_name text,
        section_name text,
        notes text default '''',
        urls jsonb not null default ''[]''::jsonb,
        created_at timestamptz not null default now()
      )',
      relation_name
    );

    execute format(
      'grant select, insert, update, delete on table public.%I to anon, authenticated',
      relation_name
    );

    sequence_name := pg_get_serial_sequence(format('public.%I', relation_name), 'id');
    if sequence_name is not null then
      execute format('grant usage, select on sequence %s to anon, authenticated', sequence_name);
    end if;
  end loop;
end
$$;
