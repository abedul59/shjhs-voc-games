create table if not exists public.class_focus_monitor_sessions (
  id bigint generated by default as identity primary key,
  target_key text not null,
  target_type text not null check (target_type in ('regular', 'special')),
  target_label text not null,
  class_name text,
  special_class_id text,
  title text not null default '班級專注監控',
  status text not null default 'active' check (status in ('active', 'ended')),
  heartbeat_interval_seconds integer not null default 15 check (heartbeat_interval_seconds between 10 and 60),
  warning_after_seconds integer not null default 45 check (warning_after_seconds between 20 and 300),
  offline_after_seconds integer not null default 90 check (offline_after_seconds between 30 and 600),
  started_at timestamptz not null default now(),
  ended_at timestamptz,
  created_at timestamptz not null default now(),
  constraint class_focus_monitor_threshold_order check (offline_after_seconds > warning_after_seconds)
);

create unique index if not exists class_focus_monitor_one_active_target_idx
  on public.class_focus_monitor_sessions (target_key)
  where status = 'active';

create index if not exists class_focus_monitor_sessions_recent_idx
  on public.class_focus_monitor_sessions (target_key, started_at desc);

create table if not exists public.class_focus_monitor_presence (
  session_id bigint not null references public.class_focus_monitor_sessions(id) on delete cascade,
  student_id text not null,
  student_name text not null default '',
  class_name text not null default '',
  browser_id text not null default '',
  visibility_state text not null default 'visible',
  current_path text not null default '/',
  last_event text not null default 'heartbeat',
  first_seen_at timestamptz not null default now(),
  last_heartbeat_at timestamptz not null default now(),
  updated_at timestamptz not null default now(),
  primary key (session_id, student_id)
);

create index if not exists class_focus_monitor_presence_recent_idx
  on public.class_focus_monitor_presence (session_id, last_heartbeat_at desc);

create table if not exists public.class_focus_monitor_events (
  id bigint generated by default as identity primary key,
  session_id bigint not null references public.class_focus_monitor_sessions(id) on delete cascade,
  student_id text not null,
  event_type text not null,
  current_path text not null default '/',
  visibility_state text not null default 'visible',
  occurred_at timestamptz not null default now()
);

create index if not exists class_focus_monitor_events_recent_idx
  on public.class_focus_monitor_events (session_id, occurred_at desc);

grant select, insert, update, delete on public.class_focus_monitor_sessions to anon, authenticated;
grant select, insert, update, delete on public.class_focus_monitor_presence to anon, authenticated;
grant select, insert, update, delete on public.class_focus_monitor_events to anon, authenticated;
grant usage, select on sequence public.class_focus_monitor_sessions_id_seq to anon, authenticated;
grant usage, select on sequence public.class_focus_monitor_events_id_seq to anon, authenticated;

comment on table public.class_focus_monitor_sessions is '教師主動啟動的班級專注監控場次。';
comment on table public.class_focus_monitor_presence is '學生在監控場次中的最新心跳與可見狀態。';
comment on table public.class_focus_monitor_events is '監控場次中的加入、分頁切換、頁面切換與離開事件。';
