create table if not exists public.class_game_unlock_rules (
  id bigint generated by default as identity primary key,
  class_name text not null,
  name text not null,
  source_game_ids text[] not null default '{}',
  target_game_ids text[] not null default '{}',
  requirement_scope jsonb not null default '{"mode":"ALL","scopes":[]}'::jsonb,
  condition_mode text not null default 'plays' check (condition_mode in ('plays', 'score', 'either', 'both')),
  required_plays integer not null default 1 check (required_plays >= 0),
  required_score numeric not null default 0 check (required_score >= 0),
  enabled boolean not null default true,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now()
);

create index if not exists class_game_unlock_rules_class_idx
  on public.class_game_unlock_rules (class_name, enabled);

create table if not exists public.student_game_unlock_overrides (
  id bigint generated by default as identity primary key,
  rule_id bigint not null references public.class_game_unlock_rules(id) on delete cascade,
  student_id text not null,
  override_mode text not null default 'inherit' check (override_mode in ('inherit', 'force_unlock', 'force_lock', 'custom')),
  required_plays integer check (required_plays is null or required_plays >= 0),
  required_score numeric check (required_score is null or required_score >= 0),
  updated_at timestamptz not null default now(),
  unique (rule_id, student_id)
);

create index if not exists student_game_unlock_overrides_student_idx
  on public.student_game_unlock_overrides (student_id, rule_id);

grant select, insert, update, delete on public.class_game_unlock_rules to anon, authenticated;
grant select, insert, update, delete on public.student_game_unlock_overrides to anon, authenticated;
grant usage, select on sequence public.class_game_unlock_rules_id_seq to anon, authenticated;
grant usage, select on sequence public.student_game_unlock_overrides_id_seq to anon, authenticated;

comment on table public.class_game_unlock_rules is '班級遊戲解鎖規則；依遊玩次數或最高分解鎖目標遊戲。';
comment on table public.student_game_unlock_overrides is '學生對班級遊戲解鎖規則的個別覆寫。';
